# description
# counting machine

# N человек, пронумерованных числами от 1 до N, стоят в кругу. Они начинают играть в считалку на
# выбывание. Каждый K-й по счёту человек выходит из круга, после чего счёт продолжается со
# следующего за ним человека. На вход подаётся количество человек N и номер K.

# task
# Напишите программу, которая выводит число от 1 до N — это номер человека, который останется в кругу последним.
# Чтобы индекс не вышел за пределы списка, нужно ограничить его рост. 
# Для этого подходит операция %: (индекс + число) % длина списка. 
# Так индекс не будет равен длине списка или не превысит её, а значит не выйдет за пределы списка.

# case
# Количество человек: 5
# Какое число в считалке? 7
# Значит, выбывает каждый 7-й человек

# Текущий круг людей: [1, 2, 3, 4, 5]
# Начало счёта с номера 1
# Выбывает человек под номером 2

# Текущий круг людей: [1, 3, 4, 5]
# Начало счёта с номера 3
# Выбывает человек под номером 5

# Текущий круг людей: [1, 3, 4]
# Начало счёта с номера 1
# Выбывает человек под номером 1

# Текущий круг людей: [3, 4]
# Начало счёта с номера 3
# Выбывает человек под номером 3

# Остался человек под номером 4

"""
Программа реализует считалку на выбывание

Процесс:
- Запрашивает количество человек
- Запрашивает шаг счёта
- Выводит текущий список игроков
- Выводит номер, с которого начинается счёт
- Рассчитывает индекс игрока, который выбывает из игры
- Удаляет элемент списка по индексу и запоминает его номер
- Изменяет индекс, с которого начинается счёт
- Выводит номер последнего оставшегося человека

Переменные:
- people_list: Список игроков
- people_count: Количество игроков
- number_counting: Шаг счёта - каждый К-й выбывает
- start_index: Индекс, с которого начинается счёт
- remove_index: Индекс выбывшего игрока
- removed: Номер игрока, удалённого из списка
"""

people_list = []

people_count = int(input('Количество человек: '))

for i in range(1, people_count + 1):
    people_list.append(i)

number_counting = int(input('Какое число в считалке? '))

print(f'Значит, выбывает каждый {number_counting}-й человек\n')

start_index = 0

while len(people_list) > 1:
    print(f'Текущий круг людей: {people_list}')
    remove_index = (start_index + number_counting - 1) % len(people_list)
    print(f'Начало счёта с номера {people_list[start_index]}')
    removed = people_list.pop(remove_index)
    print(f'Выбывает человек под номером {removed}')
    start_index = remove_index % len(people_list)
    print()

print(f'Остался человек под номером {people_list[0]}')
