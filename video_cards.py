# description
# В базе магазина электроники есть список видеокарт компании NVIDIA разных поколений.
# Вместо полных названий хранятся только числа, которые обозначают модель и поколение видеокарты.
# Недавно компания выпустила новую линейку видеокарт. Самые старшие поколения разобрали за пару дней.
# task
# Напишите программу, которая удаляет наибольшие элементы из списка видеокарт.

# Пример:
# Количество видеокарт: 5
# Видеокарта 1: 3070
# Видеокарта 2: 2060
# Видеокарта 3: 3090
# Видеокарта 4: 3070
# Видеокарта 5: 3090

# Старый список видеокарт: [ 3070 2060 3090 3070 3090 ]
# Новый список видеокарт: [ 3070 2060 3070 ]
"""
Программа удаляет наибольшие значения из списка

Процесс:
- Запрашивает количество видеокарт
- Считывает номера видеокарт и собирает в список
- Находит максимальный элемент
- Заполняет новый список без максимального значения из предыдущего списка
- Выводит информацию на экран

Переменные:
- amount_video_cards: ожидает от пользователя количество видеокарт
- number: ожидает от пользователя номер видеокарты
- max_videocards: хранит максимальное значение из списка
- list_vidocards: список видеокарт
- new_list_vidocards: новый список без максимальных значений
"""

list_vidocards = []

amount_video_cards = int(input('Количество видеокарт: '))
for i_number in range(amount_video_cards):
    number = int(input(f'Видеокарта {i_number + 1}: '))
    list_vidocards.append(number)

print(f'Старый список видеокарт: {list_vidocards}')

new_list_vidocards = []

max_videocards = list_vidocards[0]
for value in list_vidocards:
    if value > max_videocards:
        max_videocards = value

for value in list_vidocards:
    if value < max_videocards:
        new_list_vidocards.append(value)

print(f'Новый список видеокарт: {new_list_vidocards}')


