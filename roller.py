# description
# roller
# Частная контора даёт в прокат ролики самых разных размеров. Человек может надеть ролики
# только своего размера.
# Пользователь вводит два списка размеров: N размеров роликов и K размеров ног людей.
# task
# Реализуйте код, который определяет, какое наибольшее число человек может одновременно
# взять ролики и пойти кататься. 
# case
# Количество роликов: 4
# Размер пары 1: 41
# Размер пары 2: 40
# Размер пары 3: 39
# Размер пары 4: 42

# Количество людей: 3
# Размер ноги человека 1: 42
# Размер ноги человека 2: 41
# Размер ноги человека 3: 42

# Наибольшее количество людей, которые могут взять ролики: 2

"""
Программа рассчитывает, какое наибольшее число человек может одновременно взять ролики из данных, введённых пользователем

Процесс:
- Запрашивает количество роликов
- Получает размеры каждой пары роликов
- Запрашивает количество людей 
- Получает размеры ног каждого человека
- С помощью цикла проверяет, сколько людей может использовать ролики

Переменные:
- size_pair_list: Список размеров пар роликов
- size_leg_list: Список размеров ног людей
- quantity_rollers: Количество роликов
- size_pair: Размер каждого ролика
- quantity_people: Количество людей, введённое пользователем
- size_leg: Размер ноги каждого человека
- people_count: Количество людей, которые получили ролики
- used: Список индексов занятых роликов
"""

size_pair_list = []
size_leg_list = []

quantity_rollers = int(input('Количество роликов: '))

for number in range(quantity_rollers):
    size_pair = int(input(f'Размер пары {number + 1}: '))
    size_pair_list.append(size_pair)

quantity_people = int(input(f'Количество людей: '))

for number in range(quantity_people):
    size_leg = int(input(f'Размер ноги человека {number + 1}: '))
    size_leg_list.append(size_leg)

people_count = 0
used = []

for i_human in size_leg_list:
    for index, value in enumerate(size_pair_list):
        if i_human == value:
            if index not in used:
                used.append(index)
                people_count += 1
                break

print(f'Наибольшее количество людей, которые могут взять ролики: {people_count}')