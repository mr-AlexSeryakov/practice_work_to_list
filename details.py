# Напишите программу, которая запрашивает у пользователя деталь, считает их количество и
# общую стоимость.
# Пример
# Название детали: седло
# Количество деталей: 3
# Общая стоимость: 4500

shop = [['каретка', 1200], ['шатун', 1000],
        ['седло', 300], ['педаль', 100],
        ['седло', 1500], ['рама', 12000],
        ['обод', 2000], ['шатун', 200],
        ['седло', 2700]]

name = input('Название детали: ')

quantity = 0
total_price = 0

for i_name in shop:
    if name == i_name[0]:
        quantity += 1
        total_price += i_name[1]

print(f'Количество деталей: {quantity}')
print(f'Общая стоимость: {total_price}')
