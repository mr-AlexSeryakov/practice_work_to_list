# которого можно определять палиндромы, то есть слова, которые читаются одинаково слева
# направо и справа налево. При выполнении задания обязательно используйте список символов, полученный из введённого слова.

# Введите слово: мадам 
# Слово является палиндромом
# Пример 2:
# Введите слово: abccba 
# Слово является палиндромом
# Пример 3:
# Введите слово: abbd 
# Слово не является палиндромом

"""
Программа проверяет, является ли введённое слово палиндромом

Процесс:
- Полученное слово преобразует в список символов
- С помощью цикла сравнивает зеркальные пары символов
- При несовпадении останавливает проверку
- Выводит "является" / "не является" палиндромом

Переменные:
- word: Слово, введённое пользователем
- chars: Список символов введённого слова
- is_palindrome: флаг: True, если слово — палиндром, иначе False
"""

word = input('Введите слово: ')

chars = list(word)

is_palindrome = True

for i in range(len(chars) // 2):
    if chars[i] != chars[-i - 1]:
        is_palindrome = False
        break

if is_palindrome:
    print('Слово является палиндромом')
else:
    print('Слово не является палиндромом')


