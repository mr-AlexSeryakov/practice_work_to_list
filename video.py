'''
Программа создает личный список фильмов 

Процесс:
- Запрашивает какое количество необходимо добавить в библиотеку
- Сверяет наличие фильма в общей библиотеке
- При наличии фильма добавляет в личную библиотеку
- Выводит личную библиотеку на экран

Переменные:
- films: Библиотека фильмов
- my_films: Личная библиотека фильмов
- number_requests: Ожидает от пользователя количество фильмов
- name: Ожидает от пользователя наименование фильма
'''

def checking_movie(name, films):
    if name in films:
        return True
    else:
        return False

films = [
    'Крепкий орешек', 'Назад в будущее', 'Таксист',
    'Леон', 'Богемская рапсодия', 'Город грехов',
    'Мементо', 'Отступники', 'Деревня'
]

my_films = []

try:
    number_requests = int(input('Сколько фильмов хотите добавить: '))
except ValueError:
    print('Количество необходимо указать цифрами!')
else:
    for _ in range(number_requests):
        name = input('Введите название фильма: ')
        if checking_movie(name, films):
            my_films.append(name)
        else:
            print(f'Ошибка: фильма {name} у нас нет :(')
    if my_films:
        print('Ваш список любимых фильмов:', end=' ')
        print(', '.join(my_films))
    else:
        print('Ваш список пуст!')
