# desctiption
# symmetrical sequence
# Последовательность чисел называется симметричной, если она одинаково читается как слева
# направо, так и справа налево. Например, следующие последовательности являются
# симметричными:
# 1 2 3 4 5 4 3 2 1
# 1 2 1 2 2 1 2 1
# Пользователь вводит последовательность из N чисел.
# task
# Напишите программу, которая определяет,
# какое минимальное количество и каких чисел нужно добавить в конец этой последовательности,
# чтобы она стала симметричной.
# Убедитесь что ваш алгоритм работает с разными последовательностями, например с такими:
# [1, 2, 1] — в этом случае ничего добавлять не нужно.
# [1, 2, 3, 4, 3] — в этом случае надо добавить минимум, то есть числа 2 и 1.
# case
# Количество чисел: 5
# Число: 1
# Число: 2
# Число: 1
# Число: 2
# Число: 2
# Последовательность: [1, 2, 1, 2, 2]
# Нужно приписать чисел: 3
# Сами числа: [1, 2, 1]

# Количество чисел: 5
# Число: 1
# Число: 2
# Число: 3
# Число: 4
# Число: 5
# Последовательность: [1, 2, 3, 4, 5]
# Нужно приписать чисел: 4
# Сами числа: [4, 3, 2, 1]

"""
Программа запрашивает у пользователя количество чисел и сами числа,
затем определяет минимальный набор чисел, который нужно дописать
в конец, чтобы последовательность стала симметричной (палиндромом).

Процесс:
- Проверяет, что введено целое число (обрабатывает ValueError).
- Ищет самый длинный палиндромный суффикс: минимальный индекс i,
  при котором sequence_list[i:] читается одинаково в обе стороны.
- Берёт префикс sequence_list[:i], разворачивает его и добавляет в конец —
  это и есть минимальный набор чисел.
- Выводит количество добавленных чисел и сам список.
  Если последовательность уже симметрична — выводит 0 и [].

Переменные:
- count_numbers: количество вводимых чисел (int).
- sequence_list: введённая пользователем последовательность (list[int]).
- i: индекс начала палиндромного суффикса (int).
- new_list: развёрнутый префикс — числа, которые нужно дописать (list[int]).
- number: очередное введённое число (int).
"""

sequence_list = []
new_list = []

try:
    count_numbers = int(input('Количество чисел: '))
except ValueError:
    print('Необходимо указывасть числа!')
else:
    for _ in range(count_numbers):
        number = int(input(f'Число: '))
        sequence_list.append(number)

    print(f'Последовательность: {sequence_list}')

    for i in range(len(sequence_list)):
        if sequence_list[i:] == sequence_list[i:][::-1]:
            break
        
    for x in sequence_list[:i][::-1]:
        new_list.append(x)

    print(f'Нужно приписать чисел: {len(new_list)}')

    print(f'Сами числа: {new_list}')